-- Create raw tables for CSV ingestion
-- Run this before ingesting CSV data

USE SCHEMA FAN_RAW;

-- Historical shows table
CREATE OR REPLACE TABLE SHOWS_HIS (
    ARTIST_ID VARCHAR(16777216),
    ARTIST_NAME VARCHAR(16777216),
    SHOW_ID VARCHAR(16777216),
    SHOW_DATE VARCHAR(16777216),
    SOURCE VARCHAR(16777216),
    VENUE_NAME VARCHAR(16777216),
    VENUE_ID VARCHAR(16777216),
    VENUE_TYPE VARCHAR(16777216),
    VENUE_CAPACITY VARCHAR(16777216),
    CITY_NAME VARCHAR(16777216),
    STATE_CODE VARCHAR(16777216),
    COUNTRY_NAME VARCHAR(16777216),
    MARKET_SIZE VARCHAR(16777216),
    ARTIST_TIER VARCHAR(16777216),
    TICKETS_SOLD VARCHAR(16777216),
    SELLOUT_STATUS VARCHAR(16777216),
    ATTENDANCE_RATE VARCHAR(16777216),
    AVERAGE_TICKET_PRICE VARCHAR(16777216),
    TICKET_PRICE_RANGE VARCHAR(16777216),
    REVENUE VARCHAR(16777216),
    EVENT_DATE_STR VARCHAR(16777216),
    LAST_UPDATED VARCHAR(16777216),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Future shows table (with sales data)
CREATE OR REPLACE TABLE SHOWS_FUTURE (
    ARTIST_NAME VARCHAR(16777216),
    SHOW_DATE VARCHAR(16777216),
    VENUE_NAME VARCHAR(16777216),
    CITY_NAME VARCHAR(16777216),
    STATE_CODE VARCHAR(16777216),
    COUNTRY_NAME VARCHAR(16777216),
    SOURCE VARCHAR(16777216),
    COLLECTED_AT VARCHAR(16777216),
    SHOW_DATE_PARSED VARCHAR(16777216),
    SHOW_ID VARCHAR(16777216),
    VENUE_ID VARCHAR(16777216),
    TICKETS_SOLD VARCHAR(16777216),
    SELLOUT_STATUS VARCHAR(16777216),
    ATTENDANCE_RATE VARCHAR(16777216),
    AVERAGE_TICKET_PRICE VARCHAR(16777216),
    REVENUE VARCHAR(16777216),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Note: No indexes needed for raw tables
-- These tables are only used for CSV landing and dbt staging
-- dbt will create optimized tables in staging/intermediate/marts layers
